// while loop:
let index = 0
while (index <= 10) {
    // console.log(`Value of index is: ${index}`)
    index = index + 2
}


// while loop through arrays:
let myArray = ["flash", "superman", "batman"];
let arr = 0
while (arr < myArray.length) {
    // console.log(`Value of arr: ${myArray[arr]}`)
    arr = arr + 1
}


